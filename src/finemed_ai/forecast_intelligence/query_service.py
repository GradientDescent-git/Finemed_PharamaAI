    @classmethod
    def _string_column(
        cls,
        data: pd.DataFrame,
        column: str,
    ) -> pd.Series:

        if column not in data.columns:
            return pd.Series(
                "",
                index=data.index,
                dtype="object",
            )

        return (
            data[column]
            .map(cls._clean_string)
            .fillna("")
            .str.upper()
        )

    @classmethod
    def _unique_medicine_counts(
        cls,
        data: pd.DataFrame,
        category_column: str,
    ) -> dict[str, int]:

        if (
            data.empty
            or category_column
            not in data.columns
            or "Medicine_ID"
            not in data.columns
        ):
            return {}

        grouped = data[
            [
                "Medicine_ID",
                category_column,
            ]
        ].copy()

        grouped["Medicine_ID"] = (
            grouped["Medicine_ID"]
            .map(cls._normalize_medicine_id)
        )

        grouped[category_column] = (
            grouped[category_column]
            .map(cls._clean_string)
        )

        grouped = grouped.dropna(
            subset=[
                "Medicine_ID",
                category_column,
            ]
        )

        if grouped.empty:
            return {}

        counts = (
            grouped.groupby(
                category_column,
                dropna=True,
            )["Medicine_ID"]
            .nunique()
            .sort_index()
        )

        return {
            str(key): int(value)
            for key, value in counts.items()
        }

