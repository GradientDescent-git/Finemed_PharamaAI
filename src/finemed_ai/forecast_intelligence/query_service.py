    # Lookup helpers
    # ------------------------------------------------------------------

    def _medicine_lookup_frame(
        self,
    ) -> pd.DataFrame:

        if self._medicines.empty:
            return pd.DataFrame(
                columns=[
                    "Medicine_ID",
                    "Medicine_Name",
                ]
            )

        lookup = self._medicines[
            [
                "MDCODE",
                "Product_Display_Name",
            ]
        ].copy()

        lookup = lookup.rename(
            columns={
                "MDCODE": "Medicine_ID",
                "Product_Display_Name": (
                    "Medicine_Name"
                ),
            }
        )

        return lookup.drop_duplicates(
            subset=["Medicine_ID"],
            keep="first",
        )

