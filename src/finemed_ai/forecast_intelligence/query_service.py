    # ------------------------------------------------------------------

    @staticmethod
    def _require_columns(
        data: pd.DataFrame,
        required_columns: set[str],
        artifact_name: str,
    ) -> None:

        missing = sorted(
            required_columns
            - set(data.columns)
        )

        if missing:
            raise ValueError(
                f"{artifact_name.capitalize()} artifact "
                f"is missing required columns: "
                f"{', '.join(missing)}"
            )

    @classmethod
    def _normalize_query(
        cls,
        value: Any,
    ) -> str:

        if not isinstance(
            value,
            str,
        ):
            return ""

        return " ".join(
            value.strip().split()
        )

    @classmethod
    def _normalize_medicine_id(
        cls,
        value: Any,
    ) -> str | None:

        if value is None:
            return None

        try:
            if pd.isna(value):
                return None
        except TypeError:
            pass

        text = str(value).strip()

        if not text:
            return None

        if (
            text.endswith(".0")
            and text[:-2].isdigit()
        ):
            text = text[:-2]

        if text.isdigit():
            return text.zfill(4)

        return text

    @staticmethod
    def _normalize_ranking_limit(
        value: Any,
    ) -> int | None:

        if isinstance(
            value,
            bool,
        ):
            return None

        try:
            limit = int(value)
        except (
            TypeError,
            ValueError,
        ):
            return None

        if (
            limit < 1
            or limit
            > ForecastQueryService.MAX_RANKING_LIMIT
        ):
            return None

        return limit

    @staticmethod
    def _normalize_status(
        status: Any,
    ) -> str | None:

        if not isinstance(
            status,
            str,
        ):
            return None

        normalized = (
            " ".join(
                status.strip().split()
            )
            .upper()
        )

        return normalized or None

