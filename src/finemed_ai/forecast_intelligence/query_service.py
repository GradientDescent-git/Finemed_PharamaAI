    # ------------------------------------------------------------------
    # Value normalization
    # ------------------------------------------------------------------

    @staticmethod
    def _clean_string(
        value: Any,
    ) -> str | None:

        if value is None:
            return None

        try:
            if pd.isna(value):
                return None
        except TypeError:
            pass

        text = str(value).strip()

        return text or None

    @staticmethod
    def _safe_float(
        value: Any,
    ) -> float | None:

        if value is None:
            return None

        try:
            result = float(value)
        except (
            TypeError,
            ValueError,
        ):
            return None

        if not math.isfinite(result):
            return None

        return result

    @staticmethod
    def _safe_int(
        value: Any,
    ) -> int | None:

        if value is None:
            return None

        try:
            numeric = float(value)
        except (
            TypeError,
            ValueError,
        ):
            return None

        if not math.isfinite(numeric):
            return None

        return int(numeric)

    @staticmethod
    def _date_to_iso(
        value: Any,
    ) -> str | None:

        if value is None:
            return None

        try:
            if pd.isna(value):
                return None
        except TypeError:
            pass

        timestamp = pd.to_datetime(
            value,
            errors="coerce",
        )

        if pd.isna(timestamp):
            return None

        return timestamp.date().isoformat()

    @staticmethod
    def _numeric_series(
        data: pd.DataFrame,
        column: str,
    ) -> pd.Series:

        if (
            data.empty
            or column not in data.columns
        ):
            return pd.Series(
                dtype="float64"
            )

        values = pd.to_numeric(
            data[column],
            errors="coerce",
        )

        values = values.replace(
            [
                float("inf"),
                float("-inf"),
            ],
            pd.NA,
        )

        return values.dropna()

    @classmethod
    def _first_value(
        cls,
        data: pd.DataFrame,
        column: str,
    ) -> Any:

        if (
            data.empty
            or column not in data.columns
        ):
            return None

        values = data[column].dropna()

        if values.empty:
            return None

        value = values.iloc[0]

        if hasattr(
            value,
            "item",
        ):
            try:
                value = value.item()
            except ValueError:
                pass

        return cls._json_safe_value(
            value
        )

    @classmethod
    def _unique_value(
        cls,
        data: pd.DataFrame,
        column: str,
    ) -> Any:

        return cls._first_value(
            data,
            column,
        )

    @classmethod
    def _value_or_none(
        cls,
        row: pd.Series,
        column: str,
    ) -> Any:

        if column not in row.index:
            return None

        return cls._json_safe_value(
            row[column]
        )

    @classmethod
    def _float_or_none(
        cls,
        row: pd.Series,
        column: str,
    ) -> float | None:

        return cls._safe_float(
            cls._value_or_none(
                row,
                column,
            )
        )

    @classmethod
    def _int_or_none(
        cls,
        row: pd.Series,
        column: str,
    ) -> int | None:

        return cls._safe_int(
            cls._value_or_none(
                row,
                column,
            )
        )

    @staticmethod
    def _json_safe_value(
        value: Any,
    ) -> Any:

        if value is None:
            return None

        try:
            if pd.isna(value):
                return None
        except (
            TypeError,
            ValueError,
        ):
            pass

        if hasattr(
            value,
            "item",
        ):
            try:
                value = value.item()
            except (
                ValueError,
                AttributeError,
            ):
                pass

        if isinstance(
            value,
            float,
        ):
            return (
                value
                if math.isfinite(value)
                else None
            )

        return value